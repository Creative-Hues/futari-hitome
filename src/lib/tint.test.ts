import { describe, expect, it } from 'vitest';
import { multiply, multiplyMasked, paint } from './tint';

const px = (...p: number[]) => new Uint8ClampedArray(p);

describe('新しい絵に色を付ける', () => {
  it('掛け合わせ:白はその色、灰色はその分暗く、濃い線は濃いまま。濃さ(透明さ)は変えない', () => {
    const a = px(255, 255, 255, 255, 128, 128, 128, 200, 40, 40, 40, 255);
    multiply(a, [242, 166, 180]);
    expect([...a]).toEqual([242, 166, 180, 255, 121, 83, 90, 200, 38, 26, 28, 255]);
  });

  it('塗る:形(濃さ)だけ使い、選んだ色にする', () => {
    const a = px(208, 208, 208, 255, 208, 208, 208, 100, 0, 0, 0, 0);
    paint(a, [253, 251, 255]);
    expect([...a]).toEqual([253, 251, 255, 255, 253, 251, 255, 100, 253, 251, 255, 0]);
  });

  it('マスク:白いところは全部、灰色はその割合、黒・透明は色を付けない', () => {
    const body = px(255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 255, 200, 200, 200, 255);
    const mask = px(255, 255, 255, 255, 128, 128, 128, 255, 0, 0, 0, 255, 255, 255, 255, 0, 255, 255, 255, 255);
    multiplyMasked(body, mask, [166, 220, 192]);
    expect([...body]).toEqual([
      166, 220, 192, 255,
      // 半分(128/255)だけ色が付く
      210, 237, 223, 255,
      255, 255, 255, 255,
      255, 255, 255, 255,
      // 影の灰色にも掛け合わせる
      130, 173, 151, 255,
    ]);
  });
});
